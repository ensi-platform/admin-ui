/** Close when dragged past this fraction of panel height. */
export const CLOSE_THRESHOLD = 0.3;

/** Min swipe velocity (px/ms) to close. */
export const SWIPE_CLOSE_VELOCITY = 0.3;

/** Higher velocity threshold when drag started from a scroll handoff. */
export const MAX_SWIPE_CLOSE_VELOCITY = 2;

/** Scroll-handoff offset (px) that raises the velocity threshold. */
export const OFFSET_THRESHOLD = 16;

/** Min pointer movement (px) before drag starts. */
export const SWIPE_DELTA = 5;

/** Spring-back duration when swipe does not close (ms). */
export const SPRING_BACK_DURATION = 200;
